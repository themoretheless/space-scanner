def main() -> None:
    lines: list[str] = [
        "# Space Scanner — feature catalog (~1000)\n\n",
        "IDs are stable. Priority: `P0` (top-200 candidates), `P1`, `P2`.\n\n",
        "Status in this file is backlog-only; execution tracking is "
        "[ROADMAP-200.md](ROADMAP-200.md).\n\n",
    ]
    items: list[dict] = []
    fid = 1
    for cat, count in BASE_CATS:
        seed = SEEDS.get(cat, [])
        lines.append(f"## {cat}\n\n")
        for i in range(count):
            title = seed[i] if i < len(seed) else f"{cat} enhancement {i + 1 - len(seed):03d}"
            if i < 8:
                pri = "P0"
            elif i < 20:
                pri = "P1"
            else:
                pri = "P2"
            id_ = f"F{fid:04d}"
            items.append({"id": id_, "cat": cat, "title": title, "pri": pri})
            lines.append(f"- `{id_}` [{pri}] {title}\n")
            fid += 1
        lines.append("\n")

    total = fid - 1
    lines.append(f"---\n\n**Total: {total} features** across {len(BASE_CATS)} categories.\n")
    out = ROOT / "docs" / "FEATURES.md"
    out.write_text("".join(lines), encoding="utf-8")
    (ROOT / "docs" / "features_items.json").write_text(
        json.dumps(items, indent=2), encoding="utf-8"
    )
    print(f"wrote {out} ({total} features)")


if __name__ == "__main__":
    main()
